#!/usr/bin/env node
// Pulls the project's real artwork into the composition:
//  * every documentation SVG the promo shows, inlined as markup in src/brand.generated.js
//  * the extension's own UI fonts and icon, copied to assets/brand/
//
// The SVGs ship with free-running CSS @keyframes (pulse / orbit / progress / float). A render
// must be a pure function of the frame number, so the <style> block is dropped here and the
// same motions are re-driven from the HyperFrames clock in src/brand.js. Static rules (text
// font, .ink / .muted / .accent fills) are kept, scoped to each SVG so nothing leaks into the
// page, and ids are prefixed so several SVGs can live in one document.
import { copyFileSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const REPO = resolve(ROOT, "..", "..");
const A = join(REPO, ".github", "assets");

const SVGS = {
  hero: "hero-animated.svg",
  badgeVersion: "badge-v-tracker.svg",
  badgeManifest: "badge-manifest.svg",
  badgeCloudSync: "badge-cloud-sync.svg",
  headerPrivacy: "header-privacy.svg",
  headerSecurity: "header-security.svg",
  iosSettingUp: "ios-setting-up.svg",
  actionDesktop: "readme/action-desktop.svg",
  actionIphone: "readme/action-iphone.svg",
  featuresDesktop: "readme/features-desktop.svg",
  featuresMobile: "readme/features-mobile.svg",
  navSpeed: "readme/nav-speed.svg",
};
const ANIMATED = ["pulse", "orbit", "progress", "float", "drift"];

function sanitize(key, file) {
  let svg = readFileSync(join(A, file), "utf8");
  const cls = "brand-" + key;
  const styleMatch = svg.match(/<style>([\s\S]*?)<\/style>/);
  let css = "";
  if (styleMatch) {
    const body = styleMatch[1]
      .replace(/@keyframes\s+[\w-]+\s*\{(?:[^{}]*\{[^{}]*\})*[^{}]*\}/g, "")
      .replace(/@media[^{]*\{(?:[^{}]*\{[^{}]*\})*[^{}]*\}/g, "");
    for (const m of body.matchAll(/([^{}]+)\{([^{}]*)\}/g)) {
      const selectors = m[1].split(",").map((s) => s.trim()).filter(Boolean);
      const decl = m[2].split(";").map((d) => d.trim()).filter((d) => d && !/^animation/.test(d)).join(";");
      const keep = selectors.filter((s) => !ANIMATED.includes(s.replace(/^\./, "")));
      if (keep.length && decl) css += keep.map((s) => `.${cls} ${s}`).join(",") + `{${decl}}\n`;
    }
    svg = svg.replace(styleMatch[0], "");
  }
  // unique ids
  const ids = [...svg.matchAll(/\bid="([^"]+)"/g)].map((m) => m[1]);
  for (const id of new Set(ids)) {
    const re = id.replace(/[.*+?^${}()|[\]\\]/g, "\\$&");
    svg = svg
      .replace(new RegExp(`\\bid="${re}"`, "g"), `id="${key}-${id}"`)
      .replace(new RegExp(`url\\(#${re}\\)`, "g"), `url(#${key}-${id})`)
      .replace(new RegExp(`href="#${re}"`, "g"), `href="#${key}-${id}"`);
  }
  svg = svg.replace(/\saria-labelledby="[^"]*"/, "").replace(/<svg /, `<svg class="brand ${cls}" data-brand="${key}" `);
  const vb = svg.match(/viewBox="0 0 ([\d.]+) ([\d.]+)"/);
  return { svg: svg.trim(), css, width: +vb[1], height: +vb[2] };
}

const out = {};
let css = "";
for (const [key, file] of Object.entries(SVGS)) {
  const s = sanitize(key, file);
  out[key] = { svg: s.svg, width: s.width, height: s.height, source: ".github/assets/" + file };
  css += s.css;
}
// The docs use the viewer's system UI font; pin one face so the film renders the same anywhere.
css = css.replace(/font-family:[^;}]+/g, 'font-family:"Inter","Manrope",sans-serif');

const manifest = JSON.parse(readFileSync(join(REPO, "manifest.json"), "utf8"));
writeFileSync(
  join(ROOT, "src", "brand.generated.js"),
  "// Generated by tools/sync-brand-assets.mjs from .github/assets — do not edit by hand.\n" +
    "window.PROMO_BRAND = " +
    JSON.stringify({ version: manifest.version, css, assets: out }) +
    ";\n",
);

const dest = join(ROOT, "assets", "brand");
mkdirSync(dest, { recursive: true });
for (const [from, to] of [
  ["src/fonts/PROXON.ttf", "PROXON.ttf"],
  ["src/fonts/comic_sans.ttf", "comic_sans.ttf"],
  ["src/icons/icon128.png", "icon128.png"],
]) {
  copyFileSync(join(REPO, from), join(dest, to));
}
console.log(`[brand] ${Object.keys(out).length} SVGs inlined (v${manifest.version}), fonts + icon copied to assets/brand/`);
